test('длинное тире по желанию', () => {
  assert.equal(formatRef({ kind: 'book', authors: 'Иванов И.И.', title: 'А', year: '2020' }, '—'), 'Иванов, И. И. А / И. И. Иванов. — 2020. — Текст : непосредственный.')
})

test('сортировка: по алфавиту, кириллица раньше латиницы', () => {
  assert.deepEqual(sortRefs(['Smith, J. Economics', 'Яковлев, Я. Я. Б', 'Абрамов, А. А. В']), ['Абрамов, А. А. В', 'Яковлев, Я. Я. Б', 'Smith, J. Economics'])
})
