// Тесты генератора записей по ГОСТ Р 7.0.100–2018. Запуск: npm test
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { formatRef, parsePerson, sortRefs } from './gost.ts'

test('авторы в любом виде → «Иванов, И. И.»', () => {
  for (const s of ['Иванов Иван Иванович', 'Иванов И.И.', 'Иванов И. И.', 'И. И. Иванов', 'И.И. Иванов', 'Иванов, И. И.']) {
    assert.deepEqual(parsePerson(s), { last: 'Иванов', initials: ['И', 'И'] }, s)
  }
  assert.deepEqual(parsePerson('Smith John'), { last: 'Smith', initials: ['J'] })
})

