// Тесты разбора расписания из сообщения. Запуск: npm test
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { parseScheduleText } from './textSchedule.ts'

const NOW = new Date(2026, 10, 5, 12, 0) // четверг, 5 ноября 2026
const p = (s: string) => parseScheduleText(s, NOW)
const short = (s: string) => p(s).slots.map((x) => `${x.date}${x.start ? ' ' + x.start : ''}${x.end ? '-' + x.end : ''}${x.place ? ' @' + x.place : ''}`)

test('типичное сообщение организатора', () => {
  const r = p(`Репетиции посвята:
10.11 (пн) — 18:00–20:00
12.11 ср 19:00, актовый зал
15 ноября в 12:00`)
  assert.equal(r.title, 'Репетиции посвята')
  assert.deepEqual(short(`Репетиции посвята:
10.11 (пн) — 18:00–20:00
12.11 ср 19:00, актовый зал
15 ноября в 12:00`), ['2026-11-10 18:00-20:00', '2026-11-12 19:00 @актовый зал', '2026-11-15 12:00'])
})

test('время через точку и «с … до …»', () => {
  assert.deepEqual(short('11.11 19.00-21.00\n13.11 с 18 до 20'), ['2026-11-11 19:00-21:00', '2026-11-13 18:00-20:00'])
  assert.deepEqual(short('14.11 в 17.30'), ['2026-11-14 17:30'])
})

test('несколько дат в одной строке и общее время', () => {
  assert.deepEqual(short('Все репетиции 18:00–20:00\n10, 12 и 17 ноября'), ['2026-11-10 18:00-20:00', '2026-11-12 18:00-20:00', '2026-11-17 18:00-20:00'])
})

test('дни недели — ближайшие (сегодняшний тоже)', () => {
  assert.deepEqual(short('пн, ср, пт 18:00-20:00 ауд. 1413'), [
    '2026-11-06 18:00-20:00 @ауд. 1413',
    '2026-11-09 18:00-20:00 @ауд. 1413',
    '2026-11-11 18:00-20:00 @ауд. 1413',
  ])
  assert.deepEqual(short('в четверг в 19'), ['2026-11-05 19:00'])
})

test('дата строкой выше, время — строкой ниже', () => {
  assert.deepEqual(short('Понедельник 16.11:\n18:30 - 20:00, малый зал'), ['2026-11-16 18:30-20:00 @малый зал'])
})

test('завтра / послезавтра, год, прошедшие месяцы', () => {
  assert.deepEqual(short('завтра 18:00\nпослезавтра 10:00'), ['2026-11-06 18:00', '2026-11-07 10:00'])
  assert.deepEqual(short('10.01 18:00'), ['2027-01-10 18:00']) // январь уже прошёл → следующий год
  assert.deepEqual(short('20.12.2026 15:00'), ['2026-12-20 15:00'])
})

test('без даты — ничего не выдумываем', () => {
  assert.deepEqual(p('Привет! Скоро скину расписание').slots, [])
  const r = p('12.11')
  assert.deepEqual(short('12.11'), ['2026-11-12']) // время не указано — его спросит экран
  assert.equal(r.slots[0].start, '')
})

test('день недели не совпадает с датой — предупреждение', () => {
  const r = p('10.11 (пн) 18:00\n11.11 (ср) 19:00')
  assert.match(r.slots[0].warn ?? '', /«пн», а 10\.11 — вторник/)
  assert.equal(r.slots[1].warn, undefined)
})
